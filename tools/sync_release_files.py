"""Writes the files that repeat the owner's values, so that they cannot differ: CITATION.cff, .zenodo.json, the citation block in README.md,
and docs/irb-data-description.md. Their source is site_config.json, the newest entry of CHANGELOG.md, and src/analytics_schema.py.
Usage: python tools/sync_release_files.py            rewrite the files
       python tools/sync_release_files.py --check    exit 1 if a file differs from what its sources give (the static tests run this)"""
import json, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
import siteinfo, analytics_schema as AS

q = lambda s: json.dumps(s, ensure_ascii=False)
START, END = "<!-- cite:start -->", "<!-- cite:end -->"

def info(cfg):
    top = (siteinfo.changelog() or [dict(version="", date="")])[0]
    return top["version"], (top["date"] if siteinfo.ISO.match(top["date"]) else "")

def cff(cfg):
    version, date = info(cfg); A = cfg.get("authors") or []
    L = ["cff-version: 1.2.0", "message: " + q("If this site is useful in your work, cite it as below."), "type: software",
         "title: " + q(cfg.get("title") or "[title missing]"), "abstract: " + q(cfg.get("abstract") or "[abstract missing]"), "authors:"]
    for a in A:
        L += ["  - family-names: " + q(a.get("family_names", "")), "    given-names: " + q(a.get("given_names", ""))]
        if a.get("affiliation"): L.append("    affiliation: " + q(a["affiliation"]))
        if a.get("orcid"): L.append("    orcid: " + q("https://orcid.org/" + a["orcid"]))
    if not A: L.append("  - name: " + q("[authors missing]"))
    if version: L.append("version: " + q(version))
    if date: L.append("date-released: " + q(date))
    if cfg.get("repository_url"): L.append("repository-code: " + q(cfg["repository_url"]))
    if cfg.get("pages_url"): L.append("url: " + q(cfg["pages_url"]))
    L.append("license: " + siteinfo.CONTENT_LICENSES.get(cfg.get("content_license"), dict(spdx="CC-BY-4.0"))["spdx"])
    L.append("keywords:"); L += ["  - " + q(k) for k in (cfg.get("keywords") or [])]
    if cfg.get("doi"): L.append("doi: " + q(cfg["doi"]))
    return "\n".join(L) + "\n"

def zenodo(cfg):
    version, date = info(cfg); A = cfg.get("authors") or []
    creators = [dict(name=f"{a.get('family_names', '')}, {a.get('given_names', '')}", affiliation=a.get("affiliation", ""), orcid=a.get("orcid", "")) for a in A] or [dict(name="[authors missing]")]
    z = dict(title=cfg.get("title") or "[title missing]", upload_type="software", description="<p>" + (cfg.get("abstract") or "[abstract missing]") + "</p>", creators=creators,
             license=siteinfo.CONTENT_LICENSES.get(cfg.get("content_license"), dict(zenodo="cc-by-4.0"))["zenodo"], keywords=cfg.get("keywords") or [], version=version, access_right="open")
    return json.dumps(z, indent=2, ensure_ascii=False) + "\n"

def cite_block(cfg):
    version, date = info(cfg); c = siteinfo.citations(cfg, version, date[:4]); doi = cfg.get("doi")
    badge = f"[![DOI](https://zenodo.org/badge/DOI/{doi}.svg)](https://doi.org/{doi})" if doi else "DOI badge: to be added after the first Zenodo release."
    return "\n".join([START, "## How to cite", "", badge, "", "Cite the version of the site that you used. `CITATION.cff` holds the same information, and GitHub shows it under \"Cite this repository\".", "",
                      "APA", "", "> " + c["apa"], "", "AMA", "", "> " + c["ama"], "", "BibTeX", "", "```bibtex", c["bibtex"], "```", END])

def readme(cfg):
    p = ROOT / "README.md"; t = p.read_text(encoding="utf-8")
    if START not in t or END not in t: return None
    return t[:t.index(START)] + cite_block(cfg) + t[t.index(END) + len(END):]

def irb(cfg):
    be = cfg.get("analytics_backend"); code = cfg.get("analytics_site_code") or "[site code missing]"; url = cfg.get("analytics_endpoint_url") or "[endpoint URL missing]"
    ph = lambda key, what: cfg.get(key) or f"[{what}: set {key} in site_config.json]"
    L = ["# Usage data description for IRB review", "",
         "Generated by `tools/sync_release_files.py` from `src/analytics_schema.py` and `site_config.json`. Edit those files, not this one.", "",
         "## Purpose", "",
         "The study improves the practice questions of a study site for radiation oncology residents and describes how the site is used. When usage counts are on, the site records anonymous events about the questions answered and the pages used. The resident survey is separate, and the usage data are not linked to it. Only the study team sees the data. The site shows no difficulty labels and no results from other learners.", "",
         "IRB protocol: " + (cfg.get("irb_number") or "[IRB number missing: set irb_number in site_config.json]") + ".", "",
         "## Events and properties", "",
         "The site sends the events below and nothing else. A property that is not listed is dropped, and an event is not sent if a listed property is missing or its value does not fit its description.", "",
         "| Event | Sent when | Property | Values | Meaning |", "|---|---|---|---|---|"]
    for e in AS.EVENTS:
        if not e["props"]: L.append(f"| `{e['name']}` | {e['what']} | none | | |")
        for i, p in enumerate(e["props"]):
            L.append(f"| {'`' + e['name'] + '`' if i == 0 else ''} | {e['what'] if i == 0 else ''} | `{p['name']}` | {AS.values_text(p['check'])} | {p['what']} |")
    L += ["", "## Example payloads", "", "The examples use the example values in the schema.", "",
          "### Collector run by the study team", "", "Each event is an HTTP POST whose body is JSON, with no cookie and no referrer.", "", "```json"]
    L += [json.dumps(dict(event=e["name"], props=AS.example_props(e["name"]))) for e in AS.EVENTS]
    L += ["```", "", "### GoatCounter", "",
          "Each event is one request to the GoatCounter site. The request carries a path that encodes the event and a flag that marks it as an event. It carries no referrer, screen size, or page title.", "", "```"]
    L += [AS.path(e["name"], AS.example_props(e["name"])) for e in AS.EVENTS]
    L += ["```", "", "## What is not collected", ""]
    L += ["- " + x[0].upper() + x[1:] for x in AS.NEVER]
    L += ["- The text of any free-text field. The site has none.", "",
          "The site sets no cookie and writes no identifier to the browser. Its only browser storage is the learner's own progress, in keys that start with `ro.`, which never leave the device.", "",
          "## Where the data are stored", ""]
    if be == "endpoint": L += [f"A collector run by the study team at {url}. Description of the database and where it is hosted: [to be added by the study team]."]
    else: L += [f"A GoatCounter site with the code `{code}`, hosted by the GoatCounter service. The counts are held by the service for the study team's account. The service's privacy policy describes what it stores and for how long."]
    L += ["", "The site itself is a static page on GitHub Pages. GitHub keeps its own server logs for the page, as for any page it hosts.", "",
          "## Who can access the data", "", ph("data_access", "who can access the data"), "",
          "## Retention", "", ph("data_retention", "retention period"), "",
          "## Anonymity in a small cohort", "",
          "The cohort is small, so a pattern of answers or times could point to a person even without a name. The data are therefore reported as aggregates only. Any item answered fewer than 5 times is left out of anything shared outside the study team. The usage data are not linked to survey responses, and the site does not ask for a participant code.", "",
          "## To confirm before submission", "",
          "- The fields in the export of the collector, for example the date and time of each event and any short-lived session value that the service derives from the IP address and the browser string.",
          "- The retention and deletion options of the collector.",
          "- Whether the study team's reports can reveal one participant, given the number of residents who use the site.", "",
          "## Not built", "",
          "Linked analytics (`analytics_mode: \"linked\"`) is not built. It would need IRB-approved consent, a participant code that each resident enters, a secure store, and a data-use agreement.", ""]
    return "\n".join(L)

def targets(cfg):
    t = {ROOT / "CITATION.cff": cff(cfg), ROOT / ".zenodo.json": zenodo(cfg), ROOT / "docs" / "irb-data-description.md": irb(cfg)}
    r = readme(cfg)
    if r is not None: t[ROOT / "README.md"] = r
    return t

def main(argv):
    cfg = siteinfo.load_config(); t = targets(cfg); bad = []
    if not (ROOT / "README.md").read_text(encoding="utf-8").count(START): bad.append("README.md has no citation block (add the two marker lines " + START + " and " + END + ")")
    for p, text in t.items():
        have = p.read_text(encoding="utf-8") if p.exists() else None
        if "--check" in argv:
            if have != text: bad.append(f"{p.relative_to(ROOT)} is out of date: run python tools/sync_release_files.py")
        elif have != text:
            p.parent.mkdir(parents=True, exist_ok=True); p.write_text(text, encoding="utf-8"); print("wrote", p.relative_to(ROOT))
    for b in bad: print("FAIL", b)
    return 1 if bad else 0

if __name__ == "__main__": sys.exit(main(sys.argv[1:]))
